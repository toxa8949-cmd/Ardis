// Вікові підбірки дитячих велосипедів (slug виду velosyped-dytyni-X-rokiv).
// Використовується для блоку перелінковки на сторінці дитячої категорії.
export const AGE_COLLECTIONS: { age: number; slug: string }[] = SEO_COLLECTIONS
  .map((c) => {
    const m = c.slug.match(/^velosyped-dytyni-(\d+)-rokiv$/);
    return m ? { age: Number(m[1]), slug: c.slug } : null;
  })
  .filter((x): x is { age: number; slug: string } => x !== null)
  .sort((a, b) => a.age - b.age);
