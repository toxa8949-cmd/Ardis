// FAQ для SEO-лендінгів /c/[slug].
// Питання генеруються за типом підбірки (вік / колеса / ціна / гео / тип),
// щоб кожна сторінка мала унікальний корисний контент + FAQPage schema.

import type { FaqItem } from "@/lib/faq";
import type { SeoCollection } from "@/lib/seo-collections";
import { SITE } from "@/lib/site";

const DELIVERY_FAQ: FaqItem = {
  q: "Як отримати замовлення?",
  a: `Самовивіз у Києві з магазину на вул. Ревуцького, 40В (Позняки, Дарницький район) або доставка Новою Поштою по всій Україні. Зазвичай відправляємо в день замовлення або наступного дня.`,
};

const WARRANTY_FAQ: FaqItem = {
  q: "Яка гарантія на велосипеди?",
  a: "На всі велосипеди Ardis діє заводська гарантія виробника. Гарантія поширюється на раму та заводські дефекти вузлів. Деталі — на сторінці «Гарантія» або за телефоном.",
};

const TRY_FAQ: FaqItem = {
  q: "Чи можна подивитися велосипед перед покупкою?",
  a: "Так. У шоурумі на вул. Ревуцького, 40В можна оглянути велосипед наживо, сісти на нього та перевірити розмір під свій зріст. Перед візитом радимо уточнити наявність конкретної моделі телефоном.",
};

export function buildCollectionFaq(col: SeoCollection): FaqItem[] {
  const items: FaqItem[] = [];

  // Вікові підбірки.
  const ageMatch = col.slug.match(/^velosyped-dytyni-(\d+)-rokiv$/);
  if (ageMatch) {
    const age = Number(ageMatch[1]);
    items.push(
      {
        q: `Як підібрати велосипед дитині ${age} років?`,
        a: "Головний орієнтир — не вік, а зріст. Дитина, сидячи в сідлі, має впевнено діставати ногами до землі та комфортно дотягуватися до керма й гальм. Якщо дитина на межі двох розмірів — беріть більший лише тоді, коли посадка впевнена.",
      },
      {
        q: "Брати велосипед «на виріст»?",
        a: "Не радимо. Завеликий велосипед важче контролювати, дитина швидко втомлюється і може боятися кататись. Правильний розмір «тут і зараз» — це безпека та задоволення від катання.",
      }
    );
  }

  // Підбірки за діаметром коліс.
  const wheelMatch = col.slug.match(/velosypedy-(\d+(?:-\d+)?)$/);
  if (wheelMatch && !col.slug.startsWith("velosypedy-do-")) {
    const wheel = wheelMatch[1].replace("-", ".");
    items.push({
      q: `Кому підходять колеса ${wheel}"?`,
      a:
        wheel === "29"
          ? "Райдерам зростом орієнтовно від 175 см. Великі колеса краще тримають швидкість і легше долають перешкоди."
          : wheel === "27.5"
          ? "Райдерам середнього зросту, приблизно 165–180 см. Це універсальний розмір для міста й бездоріжжя."
          : wheel === "26"
          ? "Райдерам невисокого зросту та тим, хто цінує маневреність у місті. Також це перехідний розмір для високих підлітків."
          : "Дітям відповідного зросту: перевірте, щоб дитина впевнено діставала ногами до землі, сидячи в сідлі. Точні орієнтири за зростом — у описі вище.",
    });
  }

  // Цінові підбірки.
  const priceMatch = col.slug.match(/^velosypedy-do-(\d+)$/);
  if (priceMatch) {
    items.push({
      q: `Ціни в добірці актуальні?`,
      a: `Так, у добірці показані лише велосипеди з актуальною ціною до ${Number(priceMatch[1]).toLocaleString("uk-UA")} грн. Ціни та наявність оновлюються автоматично з каталогу.`,
    });
  }

  // Гео-підбірки.
  if (Object.keys(col.filters).length === 0) {
    items.push({
      q: "Де знаходиться магазин і як працює?",
      a: `Магазин Ardis — вул. Ревуцького, 40В, Київ (Позняки, Дарницький район). Телефон: ${SITE.contacts.phoneShop}. Графік роботи — на сторінці «Контакти».`,
    });
  }

  // Тип/аудиторія.
  if (col.slug === "zhinochyi-velosyped") {
    items.push({
      q: "Чим жіночий велосипед відрізняється від звичайного?",
      a: "Головна відмінність — занижена (відкрита) рама, на яку зручно сідати, та комфортна вертикальна посадка. Технічно це такі самі надійні велосипеди — обирайте за зростом і стилем катання.",
    });
  }
  if (col.slug === "miskyi-velosyped") {
    items.push({
      q: "Що входить у комплектацію міського велосипеда?",
      a: "Більшість дорожніх моделей уже укомплектовані багажником, крилами та захистом ланцюга — можна їздити одразу після покупки, нічого не докуповуючи.",
    });
  }

  items.push(TRY_FAQ, DELIVERY_FAQ, WARRANTY_FAQ);
  return items.slice(0, 5);
}
