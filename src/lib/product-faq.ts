// FAQ для картки товару (/bikes/[slug]).
// Питання й відповіді генеруються з реальних характеристик товару —
// назва, колеса, ціна, наявність — тому контент унікальний для кожної
// сторінки. Це і корисно покупцю, і додає тексту під модельні запити
// («ardis quick», «crossride 24» тощо), і дає FAQPage schema.

import type { FaqItem } from "@/lib/faq";
import type { Product } from "@/types";
import { uah, SITE } from "@/lib/site";

// Орієнтири зросту/віку за діаметром колеса.
const WHEEL_FIT: Record<string, string> = {
  "12": "дітям приблизно 2–4 років зростом 90–105 см",
  "14": "дітям приблизно 3–5 років зростом 100–110 см",
  "16": "дітям приблизно 4–6 років зростом 100–120 см",
  "18": "дітям приблизно 5–7 років зростом 110–125 см",
  "20": "дітям приблизно 6–9 років зростом 115–135 см",
  "24": "підліткам приблизно 10–13 років зростом 135–155 см",
  "26": "райдерам невисокого та середнього зросту (орієнтовно 155–175 см) — точніше підкаже розмір рами",
  "27.5": "райдерам середнього зросту, приблизно 165–180 см",
  "28": "дорослим райдерам зростом від 160 см — це класичний дорожній розмір",
  "29": "райдерам зростом від 175 см",
};

export function buildProductFaq(p: Product): FaqItem[] {
  const items: FaqItem[] = [];
  const isKids = ["12", "14", "16", "18", "20"].includes(p.wheel_size ?? "");

  // Наявність і ціна — найчастіше питання.
  items.push({
    q: `${p.name} — є в наявності? Яка ціна?`,
    a: p.in_stock
      ? `Так, ${p.name} є в наявності за ціною ${uah(p.price)}. Можна забрати самовивозом у Києві (вул. Ревуцького, 40В, Позняки) або замовити доставку Новою Поштою по Україні. Ціна й наявність на сторінці актуальні.`
      : `Наразі ${p.name} немає в наявності. Зателефонуйте ${SITE.contacts.phoneShop} — уточнимо строки поставки або підберемо аналогічну модель.`,
  });

  // Підбір за зростом/віком — з діаметра колеса.
  if (p.wheel_size && WHEEL_FIT[p.wheel_size]) {
    items.push({
      q: isKids
        ? `На який вік і зріст підходить ${p.name}?`
        : `На який зріст підходить ${p.name}?`,
      a: `${p.name} має колеса ${p.wheel_size}" і підходить ${WHEEL_FIT[p.wheel_size]}. ${
        isKids
          ? "Найнадійніша перевірка: дитина, сидячи в сідлі, має впевнено діставати ногами до землі."
          : "Якщо вагаєтесь із розміром рами — скористайтеся калькулятором ростовки на головній або зателефонуйте, підкажемо."
      }`,
    });
  }

  // Доставка.
  items.push({
    q: `Як швидко доставите ${isKids ? "дитячий велосипед" : "велосипед"}?`,
    a: "Відправка Новою Поштою зазвичай у день замовлення або наступного дня; доставка по Україні займає 1–3 дні. Самовивіз у Києві — можна забрати одразу після підтвердження наявності.",
  });

  // Гарантія.
  items.push({
    q: `Яка гарантія на ${p.name}?`,
    a: "Заводська гарантія виробника — поширюється на раму та заводські дефекти вузлів. Велосипед проходить передпродажну підготовку перед видачею чи відправкою.",
  });

  return items;
}
