// Лейаут російського розділу — виправляє мовну позначку документа.
//
// КОНТЕКСТ: у App Router тег <html> рендерить лише кореневий layout.tsx,
// і там жорстко стоїть lang="uk". Дізнатись поточний шлях у кореневому
// лейауті можна тільки через headers(), але це вимкнуло б статичну
// генерацію для ВСЬОГО сайту — ціна невиправдана заради одного атрибута.
//
// Тому виставляємо lang="ru" вбудованим скриптом. Він виконується до
// першого малювання, Googlebot рендерить JS і бачить коректне значення,
// а екранні читалки й автоперекладач браузера отримують правильну мову.
// Кореневий lang="uk" лишається дефолтом для решти сайту.

const SET_LANG = `document.documentElement.lang="ru";`;

export default function RuLayout({ children }: { children: React.ReactNode }) {
  return (
    <>
      <script dangerouslySetInnerHTML={{ __html: SET_LANG }} />
      {children}
    </>
  );
}
